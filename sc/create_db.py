import sqlite3

db = sqlite3.connect("database.db")
cursor = db.cursor()

# Создаём таблицу меню
cursor.execute("""
CREATE TABLE IF NOT EXISTS menu (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    name TEXT,
    price INTEGER,
    calories INTEGER,
    proteins REAL,
    fats REAL,
    carbs REAL,
    category TEXT,
    contains_milk INTEGER
)
""")

cursor.execute("DELETE FROM menu")

